export function modulePermission(module: string, action: ModuleAction | string): string {
  return `${module}.${action}`;
}

function allModuleActions(module: string, actions: readonly ModuleAction[] = MODULE_ACTIONS): string[] {
  return actions.map((a) => modulePermission(module, a));
}

