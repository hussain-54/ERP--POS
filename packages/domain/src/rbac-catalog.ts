function unique(keys: string[]): string[] {
  return [...new Set(keys)].sort();
}

/** Alias map so new CRUD keys satisfy legacy route checks. */
export const PERMISSION_ALIASES: Record<string, string[]> = {
  "products.read": ["products.view"],
  "products.write": ["products.add", "products.edit"],
  "products.delete": ["products.delete"],
  "customers.read": ["customers.view"],
  "customers.write": ["customers.add", "customers.edit"],
  "purchases.read": ["purchases.view"],
  "purchases.write": ["purchases.add", "purchases.edit"],
  "accounts.read": ["accounts.view"],
  "accounts.write": ["accounts.add", "accounts.edit"],
  "expenses.manage": ["expenses.view", "expenses.add", "expenses.edit", "expenses.approve"],
  "banking.manage": ["banking.view", "banking.add", "banking.edit"],
  "inventory.view": ["inventory.view"],
};

export function permissionSatisfied(granted: string[], required: string): boolean {
  if (granted.includes(required)) return true;
  if (granted.includes("*")) return true;
  // Legacy key required, user has new CRUD key
  const aliases = PERMISSION_ALIASES[required];
  if (aliases?.some((a) => granted.includes(a))) return true;
  // New key required, user has legacy manage/write/read
  for (const [legacy, news] of Object.entries(PERMISSION_ALIASES)) {
    if (news.includes(required) && granted.includes(legacy)) return true;
  }
  return false;
}
